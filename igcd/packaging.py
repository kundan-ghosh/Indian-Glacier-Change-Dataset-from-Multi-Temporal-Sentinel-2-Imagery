"""Dataset packaging and split generation for deep learning workflows."""

from __future__ import annotations

import json
import shutil
from pathlib import Path
from typing import Iterable

import pandas as pd


def assign_group_splits(
    glacier_ids: Iterable[str],
    split_ratios: dict[str, float],
    seed: int = 42,
) -> pd.DataFrame:
    """Assign glacier-level train/validation/test splits deterministically."""

    ids = pd.Series(sorted(set(glacier_ids)), name="glacier_id")
    shuffled = ids.sample(frac=1.0, random_state=seed).reset_index(drop=True)
    n = len(shuffled)
    train_end = int(round(n * split_ratios["train"]))
    val_end = train_end + int(round(n * split_ratios["validation"]))
    split = pd.Series("test", index=shuffled.index, dtype="object")
    split.iloc[:train_end] = "train"
    split.iloc[train_end:val_end] = "validation"
    return pd.DataFrame({"glacier_id": shuffled, "split": split})


def package_dataset(
    inventory: pd.DataFrame,
    image_paths: dict[tuple[str, int], Path],
    label_paths: dict[str, Path],
    output_dir: str | Path,
    split_ratios: dict[str, float],
    metadata: dict[str, object],
) -> dict[str, Path]:
    """Copy generated imagery, labels, and metadata into a model-ready layout."""

    root = Path(output_dir)
    images_dir = root / "images"
    labels_dir = root / "labels"
    metadata_dir = root / "metadata"
    for path in (images_dir, labels_dir, metadata_dir):
        path.mkdir(parents=True, exist_ok=True)

    splits = assign_group_splits(inventory["glacier_id"], split_ratios)
    splits.to_csv(metadata_dir / "splits.csv", index=False)

    copied_rows = []
    for _, row in inventory.iterrows():
        glacier_id = str(row["glacier_id"])
        split = str(
            splits.loc[splits["glacier_id"] == glacier_id, "split"].iloc[0]
        )
        for (img_glacier_id, year), source in image_paths.items():
            if img_glacier_id != glacier_id or not source.exists():
                continue
            target = images_dir / split / source.name
            target.parent.mkdir(parents=True, exist_ok=True)
            shutil.copy2(source, target)
            copied_rows.append(
                {
                    "glacier_id": glacier_id,
                    "year": year,
                    "split": split,
                    "image": str(target.relative_to(root)),
                }
            )
        label_source = label_paths.get(glacier_id)
        if label_source and label_source.exists():
            target = labels_dir / split / label_source.name
            target.parent.mkdir(parents=True, exist_ok=True)
            shutil.copy2(label_source, target)
            copied_rows.append(
                {
                    "glacier_id": glacier_id,
                    "year": "change",
                    "split": split,
                    "label": str(target.relative_to(root)),
                }
            )

    pd.DataFrame(copied_rows).to_csv(metadata_dir / "manifest.csv", index=False)
    write_dataset_metadata(root, metadata)
    return {
        "root": root,
        "splits": metadata_dir / "splits.csv",
        "manifest": metadata_dir / "manifest.csv",
    }


def write_dataset_metadata(root: Path, metadata: dict[str, object]) -> None:
    """Write dataset_info, label definitions, and dataset README."""

    metadata_dir = root / "metadata"
    label_definition = {
        "0": "Background",
        "1": "Stable Glacier",
        "2": "Glacier Retreat",
        "3": "Glacier Advance",
    }
    (metadata_dir / "dataset_info.json").write_text(
        json.dumps(metadata, indent=2, sort_keys=True),
        encoding="utf-8",
    )
    (metadata_dir / "label_definition.json").write_text(
        json.dumps(label_definition, indent=2, sort_keys=True),
        encoding="utf-8",
    )
    (root / "README.md").write_text(
        "# Indian Glacier Change Dataset\n\n"
        "This directory contains model-ready imagery, change labels, and "
        "metadata generated by the IGCD pipeline. Splits are assigned at "
        "glacier level so no glacier appears in more than one split.\n",
        encoding="utf-8",
    )

